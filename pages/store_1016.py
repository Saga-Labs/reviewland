DATA = {cc: {int(k): v for k, v in apps.items()} for cc, apps in DATA.items()}

PRIV_ORDER = {
    "us": ["Data Used to Track You", "Data Linked to You", "Data Not Linked to You", "Data Not Collected"],
    "es": ["Datos usados para rastrearte", "Datos vinculados contigo", "Datos no vinculados contigo", "No se recopilan datos"],
}


def priv(cc, app_id):
    """Privacy label as one line, e.g. 'Data Used to Track You (identifiers); Data Linked to You (identifiers)'."""
    p = DATA[cc][app_id]["priv"]
    parts = []
    for k in PRIV_ORDER[cc]:
        if k in p:
            cats = ", ".join(c.lower() for c in p[k])
            parts.append(f"{k} ({cats})" if cats else k)
    return "; ".join(parts)


def rating(cc, app_id):
    d = DATA[cc][app_id]
    return (d["rating"], d["n"])


def rating_cell(cc, app_id):
    d = DATA[cc][app_id]
    if not d["n"]:
        return "Sin valoraciones" if cc == "es" else "No ratings"
    r = f"{d['rating']:.1f}"
    n = f"{d['n']:,}"
    if cc == "es":
        return f"{r.replace('.', ',')} ({n.replace(',', '.')} {'valoración' if d['n'] == 1 else 'valoraciones'})"
    return f"{r} ({n} {'rating' if d['n'] == 1 else 'ratings'})"


def version_cell(cc, app_id):
    d = DATA[cc][app_id]
    y, m, dd = d["date"].split("-")
    mes = ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"]
    mon = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    names = mes if cc == "es" else mon
    return f"{d['ver']} ({int(dd)} {names[int(m) - 1]} {y})"


def refresh(page, cc, priv_col=3, ver_col=4, rating_col=5):
    """Fills privacy label, version and rating cells (and the JSON-LD rating) from DATA."""
    for a in page["apps"]:
        if a.get("id") and int(a["id"]) in DATA[cc]:
            i = int(a["id"])
            a["row"][priv_col] = priv(cc, i)
            a["row"][ver_col] = version_cell(cc, i)
            a["row"][rating_col] = rating_cell(cc, i)
            a["rating"] = rating(cc, i)
    return page


